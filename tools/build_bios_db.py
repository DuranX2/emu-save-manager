"""Regenerate biosdb_data.py from libretro's System.dat.

    python tools/build_bios_db.py path/to/System.dat

System.dat: https://github.com/libretro/libretro-database/blob/master/dat/System.dat
(CC BY-SA 4.0, by the libretro team).  Only names, sizes and MD5 hashes are taken;
no BIOS contents are involved.
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1])
version = "unknown"
db = {}              # md5 -> [system, [libretro names...], size]
system = None
for line in src.read_text(encoding="utf-8").splitlines():
    m = re.match(r'\s*version\s+(\S+)', line)
    if m and version == "unknown":
        version = m.group(1)
    m = re.match(r'\s*comment "(.+)"', line)
    if m and m.group(1) not in ("System", "System, firmware, and BIOS files used by libretro cores."):
        system = m.group(1)
    m = re.search(r'rom \( name "?([^"]+?)"? size (\d+) .*?md5 ([0-9a-f]{32})', line)
    if m and system:
        name, size, md5 = m.group(1), int(m.group(2)), m.group(3)
        e = db.setdefault(md5, [system, [], size])
        if name not in e[1]:
            e[1].append(name)

out = Path(__file__).resolve().parent.parent / "biosdb_data.py"
lines = ['"""BIOS fingerprints (MD5 -> system, the file names libretro cores expect, size).',
         "",
         f"Generated by tools/build_bios_db.py from libretro's System.dat {version}",
         "(https://github.com/libretro/libretro-database), licensed CC BY-SA 4.0 by the",
         "libretro team. This file is a derivative of that data and is shared under the",
         "same licence. It holds hashes and names only - no BIOS contents.",
         '"""', "", f"SOURCE_VERSION = {version!r}", "", "DB = {"]
for md5 in sorted(db, key=lambda k: (db[k][0], db[k][1][0].lower())):
    s, names, size = db[md5]
    lines.append(f"    {md5!r}: ({s!r}, {tuple(names)!r}, {size}),")
lines.append("}")
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{len(db)} fingerprints, {len({v[0] for v in db.values()})} systems -> {out.name}")
